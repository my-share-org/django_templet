"""
Django management command to synchronize system roles defined in authentication.system_roles
with the database.

Usage:
    python manage.py sync_roles
    python manage.py sync_roles --dry-run
    python manage.py sync_roles --prune
    python manage.py sync_roles --create-migration [name]
"""
import os
import re
from pathlib import Path
from django.core.management.base import BaseCommand
from authentication.services.roles import sync_system_roles


class Command(BaseCommand):
    help = "Synchronizes database Role records with canonical system role definitions in authentication.system_roles."

    def add_arguments(self, parser):
        parser.add_argument(
            "--dry-run",
            action="store_true",
            help="Simulates synchronization without persisting any database changes.",
        )
        parser.add_argument(
            "--prune",
            action="store_true",
            help="Prunes obsolete system roles from the database that are no longer defined in code.",
        )
        parser.add_argument(
            "--create-migration",
            nargs="?",
            const="sync_system_roles",
            help="Generates a new data migration that runs role synchronization during 'migrate'.",
        )

    def handle(self, *args, **options):
        create_migration_name = options.get("create_migration")

        if create_migration_name:
            self._create_migration_file(create_migration_name, prune=options["prune"])
            return

        dry_run = options["dry_run"]
        prune = options["prune"]

        if dry_run:
            self.stdout.write(
                self.style.WARNING("Running in DRY-RUN mode. No database changes will be saved.\n")
            )

        summary = sync_system_roles(prune=prune, dry_run=dry_run)

        # Output results
        if summary["created"]:
            for code in summary["created"]:
                self.stdout.write(self.style.SUCCESS(f"  [+] Created role: {code}"))

        if summary["updated"]:
            for code in summary["updated"]:
                self.stdout.write(self.style.WARNING(f"  [*] Updated role: {code}"))

        if summary["unchanged"]:
            for code in summary["unchanged"]:
                self.stdout.write(f"  [=] Unchanged role: {code}")

        if summary["pruned"]:
            for code in summary["pruned"]:
                self.stdout.write(self.style.ERROR(f"  [-] Pruned obsolete role: {code}"))

        if summary["protected_from_prune"]:
            for item in summary["protected_from_prune"]:
                self.stdout.write(
                    self.style.NOTICE(f"  [!] Protected active role from hard delete: {item}")
                )

        if summary["obsolete_unpruned"]:
            self.stdout.write(
                self.style.NOTICE(
                    "\nFound obsolete system role(s) in DB not in code (use --prune to clean up):"
                )
            )
            for item in summary["obsolete_unpruned"]:
                self.stdout.write(self.style.NOTICE(f"  - {item}"))

        total_actions = len(summary["created"]) + len(summary["updated"]) + len(summary["pruned"])
        if total_actions == 0:
            self.stdout.write(
                self.style.SUCCESS("\nAll system roles are already up to date with system_roles.py.")
            )
        else:
            status_text = "Simulated" if dry_run else "Successfully completed"
            self.stdout.write(
                self.style.SUCCESS(
                    f"\n{status_text} synchronization: "
                    f"{len(summary['created'])} created, {len(summary['updated'])} updated, "
                    f"{len(summary['unchanged'])} unchanged, {len(summary['pruned'])} pruned."
                )
            )

    def _create_migration_file(self, name: str, prune: bool = False):
        """Generates a migration file that calls sync_system_roles during 'migrate'."""
        migrations_dir = Path(__file__).resolve().parent.parent.parent / "migrations"

        # Find latest migration number
        existing_migrations = sorted(
            [f for f in os.listdir(migrations_dir) if f.endswith(".py") and f != "__init__.py"]
        )

        latest_num = 0
        latest_name = None
        for mig in existing_migrations:
            match = re.match(r"^(\d+)_", mig)
            if match:
                num = int(match.group(1))
                if num > latest_num:
                    latest_num = num
                    latest_name = mig[:-3]

        next_num = f"{latest_num + 1:04d}"
        clean_name = re.sub(r"[^a-zA-Z0-9_]", "_", name).lower()
        new_filename = f"{next_num}_{clean_name}.py"
        new_filepath = migrations_dir / new_filename

        template = f'''# Generated by sync_roles management command
from django.db import migrations


def sync_roles_forward(apps, schema_editor):
    from authentication.services.roles import sync_system_roles
    sync_system_roles(prune={prune})


def sync_roles_backward(apps, schema_editor):
    pass


class Migration(migrations.Migration):

    dependencies = [
        ("authentication", "{latest_name}"),
    ]

    operations = [
        migrations.RunPython(sync_roles_forward, reverse_code=sync_roles_backward),
    ]
'''
        with open(new_filepath, "w", encoding="utf-8") as f:
            f.write(template)

        self.stdout.write(
            self.style.SUCCESS(f"Created system role synchronization migration: {new_filename}")
        )
